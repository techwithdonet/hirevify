#!/usr/bin/env node

/**
 * HireVify Supabase Setup Script
 * Helps you manually configure Supabase connection
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const colors = {
  green: '\x1b[32m',
  red: '\x1b[31m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  reset: '\x1b[0m',
  bold: '\x1b[1m'
};

function log(message, color = colors.reset) {
  console.log(`${color}${message}${colors.reset}`);
}

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function ask(question) {
  return new Promise(resolve => {
    rl.question(`${colors.blue}${question}${colors.reset}`, resolve);
  });
}

async function main() {
  log('🚀 HireVify Supabase Setup Assistant\n', colors.bold + colors.blue);
  
  // Step 1: Get Supabase credentials
  log('📝 Step 1: Supabase Project Information', colors.bold);
  log('Get these from your Supabase dashboard: Settings → API\n');
  
  const supabaseUrl = await ask('Enter your Supabase Project URL (https://[project-id].supabase.co): ');
  const anonKey = await ask('Enter your Supabase Anon Key (starts with eyJ...): ');
  const serviceKey = await ask('Enter your Supabase Service Role Key (starts with eyJ...): ');
  
  // Extract project ID from URL
  const projectId = supabaseUrl.split('//')[1]?.split('.')[0];
  
  if (!projectId) {
    log('❌ Invalid Supabase URL format', colors.red);
    process.exit(1);
  }
  
  log(`\n✅ Project ID extracted: ${projectId}`, colors.green);
  
  // Step 2: Update environment file
  log('\n📝 Step 2: Updating Environment Variables', colors.bold);
  
  const envContent = `# HireVify Supabase Configuration
NEXT_PUBLIC_SUPABASE_URL=${supabaseUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}

# Application Configuration
NEXT_PUBLIC_APP_URL=http://localhost:3000
NODE_ENV=development

# Feature Flags
NEXT_PUBLIC_ENABLE_ANALYTICS=true
NEXT_PUBLIC_ENABLE_ERROR_REPORTING=true

# Payment Processing (Optional)
NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=pk_test_your_stripe_key
STRIPE_SECRET_KEY=sk_test_your_stripe_key
STRIPE_WEBHOOK_SECRET=whsec_your_webhook_secret
`;

  try {
    fs.writeFileSync('.env.local', envContent);
    log('✅ Created .env.local file', colors.green);
  } catch (error) {
    log(`❌ Failed to create .env.local: ${error.message}`, colors.red);
    process.exit(1);
  }
  
  // Step 3: Update Supabase info file
  log('\n📝 Step 3: Updating Supabase Info File', colors.bold);
  
  const infoContent = `/* AUTOGENERATED FILE - DO NOT EDIT CONTENTS */

export const projectId = "${projectId}"
export const publicAnonKey = "${anonKey}"
`;

  try {
    fs.writeFileSync('utils/supabase/info.tsx', infoContent);
    log('✅ Updated utils/supabase/info.tsx', colors.green);
  } catch (error) {
    log(`❌ Failed to update info file: ${error.message}`, colors.red);
    process.exit(1);
  }
  
  // Step 4: Test connection
  log('\n🧪 Step 4: Testing Connection', colors.bold);
  
  const testHealthEndpoint = async () => {
    const healthUrl = `${supabaseUrl}/functions/v1/make-server-d4feca44/health`;
    
    try {
      log(`Testing: ${healthUrl}`);
      
      const response = await fetch(healthUrl, {
        headers: {
          'Authorization': `Bearer ${anonKey}`
        }
      });
      
      if (response.ok) {
        const data = await response.json();
        log('✅ Backend is accessible!', colors.green);
        log(`📊 Status: ${data.status}`, colors.green);
        log(`🛠️  Services: ${data.services?.join(', ')}`, colors.green);
        return true;
      } else {
        log(`❌ Backend returned status ${response.status}`, colors.red);
        log('💡 You may need to deploy your Edge Functions first', colors.yellow);
        return false;
      }
    } catch (error) {
      log(`❌ Connection failed: ${error.message}`, colors.red);
      log('💡 You may need to deploy your Edge Functions first', colors.yellow);
      return false;
    }
  };

  const isConnected = await testHealthEndpoint();
  
  // Step 5: Next steps
  log('\n🎯 Next Steps:', colors.bold);
  
  if (isConnected) {
    log('✅ Your app should now be in connected mode!', colors.green);
    log('\n📋 To complete setup:', colors.blue);
    log('1. npm run dev - Start your development server');
    log('2. Check browser console for "Backend is accessible"');
    log('3. Your app should show dashboards instead of offline mode');
  } else {
    log('⚠️  Your Edge Functions need to be deployed', colors.yellow);
    log('\n📋 To complete setup:', colors.blue);
    log('1. Install Supabase CLI: npm install -g supabase');
    log('2. Login: supabase login');
    log(`3. Deploy functions: supabase functions deploy server --project-ref ${projectId}`);
    log('4. Run this script again to test connection');
    log('5. Start dev server: npm run dev');
  }
  
  log('\n📖 For detailed instructions, see: MANUAL_SUPABASE_SETUP.md', colors.blue);
  
  // Create deployment script
  const deployScript = `#!/bin/bash
echo "🚀 Deploying HireVify Edge Functions"
echo "Project ID: ${projectId}"

# Deploy to Supabase
supabase functions deploy server --project-ref ${projectId}

# Test deployment
curl -H "Authorization: Bearer ${anonKey}" \\
  ${supabaseUrl}/functions/v1/make-server-d4feca44/health

echo "✅ Deployment complete!"
`;

  try {
    fs.writeFileSync('scripts/deploy-functions.sh', deployScript);
    fs.chmodSync('scripts/deploy-functions.sh', '755');
    log('\n✅ Created deployment script: scripts/deploy-functions.sh', colors.green);
  } catch (error) {
    log(`⚠️  Could not create deployment script: ${error.message}`, colors.yellow);
  }
  
  rl.close();
}

// Check for fetch availability (Node 18+)
if (typeof fetch === 'undefined') {
  console.log('Installing node-fetch for testing...');
  try {
    global.fetch = require('node-fetch');
  } catch (e) {
    console.log('Installing node-fetch...');
    require('child_process').execSync('npm install node-fetch', { stdio: 'inherit' });
    global.fetch = require('node-fetch');
  }
}

main().catch(console.error);